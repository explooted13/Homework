package org.example;

public class Park {
    String attractionName;
    int attractionOpenTime;
    int attractionCloseTime;
    double attractionPrice;

    public Park(String attractionName, int attractionOpenTime, int attractionCloseTime, double attractionPrice){
        this.attractionName = attractionName;
        this.attractionOpenTime = attractionOpenTime;
        this.attractionCloseTime = attractionCloseTime;
        this.attractionPrice = attractionPrice;
    }
}
